package com.openrayneo.android

import okhttp3.Request
import okhttp3.Response
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject

/** Bounded client-side function calls for explicitly requested work, sharing the
 * selected model and the existing local approval/execution gate. No hosted MCP,
 * tool search, ambient tool calls, or cross-provider fallback. */
internal object SelectedModelToolTransport {
    private const val MAX_BYTES = 2L * 1024 * 1024
    const val MAX_CALLS = 6
    const val MAX_ROUNDS = 5
    data class ToolCall(val id: String, val name: String, val arguments: JSONObject)
    data class Turn(val answer: String?, val model: String?, val calls: List<ToolCall>, val replay: JSONArray)
    private val groups = linkedMapOf(
        "device" to setOf("device_read", "device_brightness", "device_display", "dashboard_read", "dashboard_update", "navigation_status", "stop_navigation_mirroring"),
        "organizer" to setOf("todo_read", "todo_add", "todo_update", "todo_delete", "schedule_read", "schedule_add", "schedule_update", "schedule_delete"),
        "context" to setOf("weather_current", "weather_search_cities", "weather_get", "weather_push", "memory_reference", "about_you_read", "location_current"),
        "display" to setOf("show_notification", "display_clear", "teleprompter_start", "teleprompter_control", "record_annotate")
    )
    private val allowedNames = groups.values.flatten().toSet()
    private fun definitions(): List<JSONObject> {
        val all = CompanionTools.definitions()
        return (0 until all.length()).map { all.getJSONObject(it).getJSONObject("function") }
            .filter { it.getString("name") in allowedNames }.map {
                JSONObject(it.toString()).apply {
                    // A request id is generated by the trusted app, not the model.
                    getJSONObject("parameters").getJSONObject("properties").remove("request_id")
                    put("strict", false)
                }
            }
    }
    fun tools(responses: Boolean): JSONArray {
        val defs = definitions()
        if (!responses) return JSONArray(defs.map { JSONObject().put("type", "function").put("function", it) })
        return JSONArray(groups.map { (name, members) ->
            JSONObject().put("type", "namespace").put("name", name).put("description", "OpenRayneo local " + name + " tools")
                .put("tools", JSONArray(defs.filter { it.getString("name") in members }.map {
                    JSONObject(it.toString()).put("type", "function")
                }))
        })
    }
    private fun validType(value: Any?, schema: JSONObject): Boolean = when (schema.optString("type")) {
        "string" -> value is String && value.length <= 16_384
        "integer" -> value is Number && value.toDouble().isFinite() && value.toDouble() % 1.0 == 0.0 &&
            value.toDouble() in -9_007_199_254_740_991.0..9_007_199_254_740_991.0
        "boolean" -> value is Boolean
        "object" -> value is JSONObject && value.toString().length <= 16_384
        "array" -> value is JSONArray && value.length() <= 100 && (0 until value.length()).all {
            validType(value.opt(it), schema.getJSONObject("items"))
        }
        else -> false
    }
    fun validate(id: String, name: String, raw: String, namespace: String? = null): ToolCall {
        require(id.matches(Regex("[A-Za-z0-9_-]{1,128}"))) { "잘못된 도구 호출 ID" }
        require(name in allowedNames && (namespace == null || groups[namespace]?.contains(name) == true)) { "지원하지 않는 도구 호출" }
        require(raw.length <= 16_384) { "도구 요청 길이 초과" }
        val args = JSONObject(raw)
        val schema = definitions().single { it.getString("name") == name }.getJSONObject("parameters")
        val props = schema.getJSONObject("properties")
        val required = schema.getJSONArray("required")
        require((0 until required.length()).all { args.has(required.getString(it)) }) { "필수 도구 인자 누락" }
        require(args.keys().asSequence().all { key -> props.has(key) && validType(args.opt(key), props.getJSONObject(key)) }) {
            "도구 인자 형식 오류"
        }
        return ToolCall(id, name, args)
    }
    fun initial(profile: AiModelSelection.Profile, messages: JSONArray): JSONArray =
        if (SelectedModelTransport.usesResponses(profile)) SelectedModelTransport.subscriptionBody(profile.model, messages).getJSONArray("input")
        else JSONArray(messages.toString())

    fun request(profile: AiModelSelection.Profile, history: JSONArray): Request {
        val responses = SelectedModelTransport.usesResponses(profile)
        require(history.toString().length <= 600_000) { "업무 문맥 길이 초과" }
        val body = JSONObject().put("model", profile.model).put("tools", tools(responses)).put("parallel_tool_calls", false)
        if (responses) {
            body.put("input", history).put("store", false).put("stream", true)
            return SelectedModelTransport.responsesRequest(profile, body)
        }
        body.put("messages", history).put("stream", false)
        return Request.Builder().url(MobileModelEndpoint.resolve(profile.url, profile.key))
            .apply { if (profile.key.isNotBlank()) header("Authorization", "Bearer ${profile.key}") }
            .post(body.toString().toRequestBody("application/json".toMediaType())).build()
    }

    fun read(profile: AiModelSelection.Profile, response: Response): Turn {
        check(response.isSuccessful) { "선택 모델 업무 요청 실패 (HTTP ${response.code})" }
        val source = checkNotNull(response.body).source()
        return if (SelectedModelTransport.usesResponses(profile)) fromResponses(SelectedModelTransport.readResponsesTerminal(source))
        else {
            check(!source.request(MAX_BYTES + 1)) { "AI 응답 길이 초과" }
            fromChat(JSONObject(source.readUtf8()))
        }
    }
    fun fromResponses(terminal: SelectedModelTransport.Terminal): Turn {
        val output = terminal.response.getJSONArray("output")
        val calls = mutableListOf<ToolCall>()
        for (i in 0 until output.length()) {
            val item = output.getJSONObject(i)
            when (item.getString("type")) {
                "reasoning", "message" -> Unit
                "function_call" -> {
                    check(item.optString("status", "completed") == "completed" && !item.optBoolean("async") &&
                        (item.optJSONObject("caller")?.optString("type") ?: "direct") == "direct") { "지원하지 않는 도구 실행 형태" }
                    calls.add(validate(item.getString("call_id"), item.getString("name"), item.getString("arguments"),
                        (item.opt("namespace") as? String)?.takeIf { it.isNotBlank() }))
                }
                else -> error("지원하지 않는 모델 출력 형식")
            }
        }
        val model = terminal.response.optString("model").takeIf { it.isNotBlank() }
        return if (calls.isEmpty()) Turn(SelectedModelTransport.textAnswer(terminal).text, model, calls, JSONArray())
        else Turn(null, model, calls, output)
    }
    fun fromChat(body: JSONObject): Turn {
        val choice = body.getJSONArray("choices").getJSONObject(0)
        val message = choice.getJSONObject("message")
        val calls = message.optJSONArray("tool_calls") ?: JSONArray()
        val model = body.optString("model").takeIf { it.isNotBlank() }
        if (calls.length() == 0) {
            check(choice.optString("finish_reason") == "stop") { "AI 업무 답변 미완료" }
            val answer = message.getString("content").trim().ifBlank { error("빈 AI 업무 답변") }
            return Turn(answer, model, emptyList(), JSONArray())
        }
        check(choice.optString("finish_reason") == "tool_calls") { "AI 도구 호출 미완료" }
        val parsed = (0 until calls.length()).map {
            val call = calls.getJSONObject(it); require(call.getString("type") == "function")
            val fn = call.getJSONObject("function")
            validate(call.getString("id"), fn.getString("name"), fn.getString("arguments"))
        }
        val replay = JSONObject().put("role", "assistant").put("content", message.opt("content") ?: JSONObject.NULL).put("tool_calls", calls)
        // Some Chat Completions-compatible reasoning models require the opaque
        // reasoning_content field to continue a tool turn; do not display it.
        message.opt("reasoning_content")?.let { replay.put("reasoning_content", it) }
        return Turn(null, model, parsed, JSONArray().put(replay))
    }
    fun append(history: JSONArray, turn: Turn) {
        for (i in 0 until turn.replay.length()) history.put(turn.replay.get(i))
    }
    fun appendResult(profile: AiModelSelection.Profile, history: JSONArray, call: ToolCall, result: JSONObject) {
        val value = result.toString()
        check(value.length <= 80_000) { "도구 결과가 너무 큽니다. 조회 범위를 좁혀 다시 요청하세요." }
        history.put(if (SelectedModelTransport.usesResponses(profile))
            JSONObject().put("type", "function_call_output").put("call_id", call.id).put("output", value)
        else JSONObject().put("role", "tool").put("tool_call_id", call.id).put("content", value))
    }
}
